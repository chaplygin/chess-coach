package org.chesscoach.coach.text

/**
 * Термины, не всегда знакомые клубному игроку рейтинга 1200–1800 и поэтому
 * получающие короткую сноску в конце разбора при первом упоминании.
 *
 * Более простые термины — вилка, связка, форпост, отсталая пешка, проходная,
 * качество — сюда намеренно не входят: клубный игрок такого уровня их и так
 * знает, а объяснять очевидное — тон учебника для начинающих, а не тренера.
 *
 * [label] — как термин называется сам по себе (для блока сносок), отдельно от
 * [phrase][Glossary.mention], которым он вписан в конкретное предложение
 * ("плохим слоном", "Перегруженный конь") — падеж и род там свои у каждого
 * случая, а сноска всегда одна и та же.
 */
enum class GlossaryTerm(val label: String, val definition: String) {
    OVERLOADED_PIECE("перегруженная фигура", "одна фигура отвечает сразу за два дела и не может успеть в оба"),
    XRAY("рентген", "дальше по линии стоит фигура ценнее той, что впереди — уйдёт передняя, достанется ей"),
    BAD_BISHOP("плохой слон", "слон упирается в собственные пешки того же цвета и лишён простора"),
}

/**
 * Отслеживает, какие термины встретились в пределах одного разбора.
 *
 * Пояснение раньше вклинивалось прямо в предложение скобками — "Рентген
 * (дальше по линии...) по линии от b6" читать невозможно. Теперь [mention]
 * только запоминает термин и возвращает фразу как есть, а все пояснения
 * рендерер сводит в один короткий блок в конце разбора — так само предложение
 * остаётся цельным.
 *
 * Каждый вызов [org.chesscoach.coach.text.TextRenderer.render] заводит свой
 * экземпляр: список сносок не должен ни расти внутри одного разбора при
 * повторных упоминаниях, ни просочиться состоянием в следующую позицию.
 */
class Glossary {

    private val mentioned = linkedSetOf<GlossaryTerm>()

    /** [phrase] — само упоминание термина в тексте, например "плохим слоном"; возвращается без изменений. */
    fun mention(term: GlossaryTerm, phrase: String): String {
        mentioned += term
        return phrase
    }

    /** Термины, прозвучавшие в этом разборе, в порядке первого упоминания — материал для блока сносок. */
    fun footnotes(): List<GlossaryTerm> = mentioned.toList()
}
