package org.chesscoach.coach.text

/**
 * Русская фигурная нотация вместо латинской: K→Кр, Q→Ф, R→Л, B→С, N→К.
 *
 * Замена — один проход по символам SAN-строки символ за символом, а не
 * цепочка последовательных `.replace(...)`. Английские K (король) и N (конь)
 * заменяются каждый на свою русскую букву, и при небрежной цепочке замен
 * результат одного правила ("N" → "К") тут же попадает под другое ("К" →
 * "Кр"), схлопывая коня с королём. Один проход по исходной строке этого не
 * допускает: решение для каждого символа принимается один раз и только по
 * исходному символу.
 *
 * Поля доски пишутся строчными буквами (e4, c7) и ни под одно из правил не
 * попадают. Взятия (x), шах (+), мат (#), превращение (=) и рокировка (O-O,
 * O-O-O) не тронуты — из шести заменяемых букв ни одна не встречается в этих
 * обозначениях.
 */
object SanRuFormatter {

    private val pieceLetters = mapOf(
        'K' to "Кр",
        'Q' to "Ф",
        'R' to "Л",
        'B' to "С",
        'N' to "К",
    )

    /** Один ход в SAN, например "Nbd2+", "Kd2" или "O-O". */
    fun move(san: String): String = buildString(san.length + 1) {
        for (ch in san) append(pieceLetters[ch] ?: ch.toString())
    }

    /** Несколько ходов подряд через пробел — для вариантов и продолжений. */
    fun line(sanMoves: List<String>): String = sanMoves.joinToString(" ") { move(it) }
}
