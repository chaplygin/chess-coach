package org.chesscoach.coach.text

/**
 * Запись хода для показа человеку.
 *
 * Сейчас — латинская нотация без изменений, та же, что приходит от движка и
 * от Lichess. Русская фигурная нотация (K→Кр, Q→Ф, R→Л, B→С, N→К) тут была и
 * оказалась хуже: переводился только текст тренера, а лента ходов и строка
 * «Лучший ход» показывали исходную латиницу. Один и тот же ход выглядел на
 * одном экране как Bd7 и как Сd7 — читатель видел не две традиции записи, а
 * ошибку. Цена единообразия выше красоты: сверять разбор с lichess.org в
 * латинице тоже проще.
 *
 * [RUSSIAN_PIECE_LETTERS] возвращает прежнее поведение одной правкой, но
 * менять его в одиночку нельзя: латиницу показывают ещё лента ходов и
 * карточка быстрой оценки в :app, и они должны переключиться вместе.
 */
object SanRuFormatter {

    private const val RUSSIAN_PIECE_LETTERS = false

    private val pieceLetters = mapOf(
        'K' to "Кр",
        'Q' to "Ф",
        'R' to "Л",
        'B' to "С",
        'N' to "К",
    )

    /** Один ход в SAN, например "Nbd2+", "Kd2" или "O-O". */
    fun move(san: String): String {
        if (!RUSSIAN_PIECE_LETTERS) return san
        // Замена одним проходом по исходной строке, а не цепочкой replace:
        // иначе результат правила "N" → "К" тут же попадёт под "K" → "Кр" и
        // конь схлопнется с королём.
        return buildString(san.length + 1) {
            for (ch in san) append(pieceLetters[ch] ?: ch.toString())
        }
    }

    /** Несколько ходов подряд через пробел — для вариантов и продолжений. */
    fun line(sanMoves: List<String>): String = sanMoves.joinToString(" ") { move(it) }
}
