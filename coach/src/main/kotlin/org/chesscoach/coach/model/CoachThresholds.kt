package org.chesscoach.coach.model

/**
 * Пороги в одном месте.
 *
 * Разбросанные по детекторам числа невозможно откалибровать: правишь один,
 * забываешь второй, и тренер начинает противоречить сам себе.
 */
object CoachThresholds {
    /** Ниже этого угроза не печатается вообще. */
    const val THREAT_MIN_CP = 60

    /** Выше этого формулировка усиливается. */
    const val THREAT_STRONG_CP = 150

    /** Насколько ход должен ослабить угрозу, чтобы считаться профилактикой. */
    const val PROPHYLAXIS_MIN_DROP_CP = 40

    /** Ловушка показывается, только если она реально дорого стоит. */
    const val TRAP_MIN_LOSS_CP = 100

    /** Сколько причин показываем: список из семи пунктов не запоминается. */
    const val MAX_REASONS = 3

    /** Заметный перевес в подвижности. */
    const val MOBILITY_EDGE = 6

    /** Заметный перевес в контроле центра. */
    const val CENTER_EDGE = 2

    /** Материал считается неравным начиная с этой разницы. */
    const val MATERIAL_NOTE_CP = 90
}
