package org.chesscoach.core

/**
 * Перевод оценки позиции в точку графика партии.
 *
 * Отдельно от [ScoreFormat] — тому нужна печатная строка, здесь нужно число на
 * отрезке для рисования одним Canvas, и смешивать эти две задачи незачем.
 */
object EvalGraph {

    /**
     * Сантипешки, дальше которых линия просто упирается в край графика.
     *
     * Без предела один зевок мата (десятки тысяч условных сантипешек во
     * внутренней шкале оценки) растянул бы график так, что вся остальная
     * партия легла бы плоской линией у нуля.
     */
    private const val CLAMP_CP = 800

    /**
     * Оценка от лица белых на отрезке [-1, 1]: 1 — верх графика, у белых
     * выигрышная позиция; -1 — низ, выигрывают чёрные.
     *
     * Мат сворачивается в упор в край, а не в гигантское число — по той же
     * причине, что и обычная оценка: длинная линия не должна теряться на его
     * фоне.
     */
    fun fraction(scoreWhite: Score): Double = when (scoreWhite) {
        is Score.Mate -> if (scoreWhite.movesToMate >= 0) 1.0 else -1.0
        is Score.Cp -> (scoreWhite.centipawns.toDouble() / CLAMP_CP).coerceIn(-1.0, 1.0)
    }
}
